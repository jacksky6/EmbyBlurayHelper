// Isolated browser regression checks against the published app. Never connects to a real Emby.
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const net = require('node:net');
const { spawn } = require('node:child_process');
const { chromium } = require(process.argv[2]);
const executable = path.resolve(process.argv[4] || 'artifacts/checks/app-win-x64/EmbyBlurayHelper.exe');
const assert = (value, message) => { if (!value) throw new Error(message); };
const port = () => new Promise(resolve => { const server = net.createServer(); server.listen(0,'127.0.0.1',()=>{const number=server.address().port;server.close(()=>resolve(number));}); });
(async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(),'bluray-status-ui-'));
  const managementPort = await port(), proxyPort = await port();
  fs.writeFileSync(path.join(directory,'settings.json'),JSON.stringify({managementUrl:`http://127.0.0.1:${managementPort}`,proxyUrl:`http://127.0.0.1:${proxyPort}`,embyUrl:'http://127.0.0.1:1',upstreamProbePath:'',embyApiKey:'fixture-key',enableProbeLanguagePatch:false,enableInfuseLanguagePatch:true}));
  const processHandle = spawn(executable,['--serve','--data-dir',directory],{windowsHide:true,stdio:'ignore'});
  const origin = `http://127.0.0.1:${managementPort}`;
  let browser;
  try {
    for(let attempt=0;;attempt++) {
      try { if((await fetch(origin)).ok) break; } catch {}
      if(attempt===100) throw new Error('Isolated helper did not start');
      await new Promise(resolve=>setTimeout(resolve,100));
    }
    browser = await chromium.launch({headless:true,executablePath:process.argv[3]});
    const context = await browser.newContext({viewport:{width:1440,height:1080}});
    const page = await context.newPage();
    const errors=[]; page.on('pageerror',error=>errors.push(error.message));
    let current = {state:'disconnected',languagePatchEnabled:false,customProbeEnabled:false,currentProbePath:'original',canApply:true,canRestore:false,message:null};
    let failRead=false, failMutation=false, mutations=0, reads=0, holdRead;
    let discovery={path:executable,accessible:true,message:'已从 Emby 获取原版 ffprobe 路径。'};
    let discoveryError=false, discoveryCalls=0;
    await page.route('**/api/probe/status',async route=>{
      reads++;
      if(holdRead) await holdRead;
      if(failRead) return route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'fixture: Emby 暂时不可达'})});
      return route.fulfill({json:current});
    });
    await page.route('**/api/emby/test',route=>route.fulfill({json:{name:'Test Emby',version:'4.10.2.0',apiAuthenticated:true,originalProbePath:discovery.path,originalProbeAccessible:discovery.accessible}}));
    await page.route('**/api/probe/discover',route=>{
      discoveryCalls++;
      const input=route.request().postDataJSON();
      assert(input.embyUrl==='http://127.0.0.1:1' && input.embyApiKey==='fixture-key','discovery uses address and key from the form');
      return discoveryError ? route.fulfill({status:400,json:{error:'fixture: API key 验证失败'}}) : route.fulfill({json:discovery});
    });
    await page.route('**/api/probe/toggle',async route=>{
      mutations++;
      if(failMutation) return route.fulfill({status:400,json:{error:'fixture: 切换失败'}});
      const {enabled}=route.request().postDataJSON();
      current={...current,state:enabled?'connected':'disconnected',languagePatchEnabled:enabled,customProbeEnabled:enabled,currentProbePath:enabled?executable:'original',canApply:!enabled,canRestore:enabled};
      const saved=(await (await context.request.get(origin+'/api/settings')).json()).settings;
      await context.request.post(origin+'/api/settings',{headers:{'X-Helper-Request':'1'},data:{...saved,enableProbeLanguagePatch:enabled}});
      return route.fulfill({json:{enabled,status:current,message:enabled?'已开启语言补全并接入 Emby。':'已关闭语言补全，已恢复原探测器配置。'}});
    });
    await page.goto(origin+'/#features');
    await page.locator('#username').fill('admin'); await page.locator('#password').fill('123456');
    await page.locator('#login-form button').click();
    await page.locator('#console').waitFor({state:'visible'});
    const checkState=async(state,checked)=>{
      await page.locator(`#probe-integration[data-state="${state}"]`).waitFor();
      if(checked!==undefined) assert(await page.locator('#enable-probe').isChecked()===checked,`${state}: switch must reflect effective state`);
      assert(await page.locator('#apply-probe,#restore-probe').count()===0,'separate integration buttons removed');
    };
    const refresh=async()=>{
      const response=page.waitForResponse(r=>r.url().endsWith('/api/probe/status'));
      await page.locator('#refresh-probe').click(); await response;
    };
    fs.mkdirSync('artifacts/ui',{recursive:true});
    const screenshot=async name=>{await page.locator('#toast').evaluate(el=>el.hidden=true);return page.screenshot({path:`artifacts/ui/probe-${name}.png`,fullPage:true,mask:[page.locator('#api-key')]});};
    await checkState('disconnected',false); await screenshot('disconnected');
    assert(reads===1,'initial page reads integration exactly once');
    await page.clock.install();
    const beforeIdle=reads;
    await page.clock.fastForward(60000);
    await page.evaluate(()=>fetch('/api/status'));
    assert(reads===beforeIdle,'idle page never polls Emby integration');
    await page.locator('#enable-probe').setChecked(true);
    await checkState('connected',true);
    assert((await page.locator('#probe-patch-state').textContent()).includes('已启用'),'connected state displays enabled patch');
    await screenshot('connected');
    assert(mutations===1,'turning on switches probe without a separate save');
    await page.locator('#enable-probe').setChecked(false);
    await checkState('disconnected',false);
    assert(mutations===2,'turning off restores original probe immediately');
    await page.locator('#enable-probe').setChecked(true); await checkState('connected',true);
    const beforeSave=mutations;
    await page.locator('#save-features').click();
    await page.locator('#toast').filter({hasText:'设置已保存'}).waitFor();
    await checkState('connected',true);
    assert(mutations===beforeSave,'saving other preferences does not switch the probe again');
    await page.reload(); await page.locator('#console').waitFor({state:'visible'}); await checkState('connected',true);
    const beforeNavigate=reads;
    await page.locator('[data-page="overview"]').click();
    await page.locator('#probe-integration[data-state="connected"]').waitFor({state:'attached'});
    assert((await page.locator('#probe-state').textContent()).includes('已接入 · 补全已启用'),'overview reflects actual integration state');
    await page.locator('[data-page="features"]').click();
    await checkState('connected',true);
    assert(reads===beforeNavigate+2,'entering overview and features checks each page once');
    await page.locator('#enable-probe').setChecked(false); await checkState('disconnected',false);
    current={...current,state:'other',customProbeEnabled:true,currentProbePath:'/other/probe',canApply:true,canRestore:false};
    await refresh(); await checkState('other',false);
    await screenshot('other');
    const beforeCancel=mutations;
    await page.locator('#enable-probe').setChecked(true);
    assert((await page.locator('#dialog-title').textContent()).includes('替换'),'replacement confirmation names current probe');
    await page.locator('#dialog-cancel').click();
    await checkState('other',false);
    assert(mutations===beforeCancel,'cancel restores switch and leaves other probe untouched');
    failRead=true; await refresh(); await checkState('unknown',false);
    assert(await page.locator('#probe-connection').isVisible(),'unknown offers connection help');
    assert(await page.locator('#enable-probe').isDisabled(),'unknown integration cannot be changed blindly');
    await screenshot('unknown');
    failRead=false; current={...current,state:'disconnected',canApply:true};
    let release;
    holdRead=new Promise(resolve=>release=resolve);
    await page.locator('#refresh-probe').click(); await checkState('checking');
    assert(await page.locator('#refresh-probe').isDisabled(),'read in progress cannot be submitted twice');
    release(); holdRead=null; await checkState('disconnected',false);
    failMutation=true;
    await page.locator('#enable-probe').setChecked(true);
    await page.locator('#toast').filter({hasText:'切换失败'}).waitFor();
    await checkState('disconnected',false);
    failMutation=false;
    await page.locator('#enable-probe').setChecked(true); await checkState('connected',true);
    failMutation=true;
    await page.locator('#enable-probe').setChecked(false);
    await page.locator('#toast').filter({hasText:'切换失败'}).waitFor();
    await checkState('connected',true);
    failMutation=false;
    // A connected probe without a valid backup must never offer an unsafe restore.
    current={...current,state:'connected',canApply:false,canRestore:false,currentProbePath:executable,message:'没有原探测器备份，请在 Emby 中手动恢复。'};
    await refresh(); await checkState('connected',true);
    assert(await page.locator('#probe-status-warning').isVisible(),'missing backup is explained');
    assert(await page.locator('#enable-probe').isDisabled(),'missing backup prevents unsafe restore');
    current={...current,languagePatchEnabled:false,canRestore:true,message:null}; await refresh(); await checkState('connected',false);
    assert(await page.locator('#recover-probe').isVisible(),'legacy paused integration has a recovery action');
    await screenshot('paused');
    await page.locator('#recover-probe').click(); await checkState('disconnected',false);
    await page.locator('#enable-probe').setChecked(true); await checkState('connected',true);
    await page.setViewportSize({width:390,height:844});
    await screenshot('mobile');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile layout does not overflow');
    await page.setViewportSize({width:1440,height:1080});
    await page.locator('[data-page="connection"]').click();
    await page.locator('#probe-path').fill('');
    await page.locator('#test-emby').click();
    await page.locator('#probe-discovery-result').filter({hasText:'已自动获取并保存'}).waitFor();
    assert(await page.locator('#probe-path').inputValue()===executable,'connection automatically fills original probe when the input is empty');
    let saved=(await (await context.request.get(origin+'/api/settings')).json()).settings;
    assert(saved.upstreamProbePath===executable,'automatically obtained original path is saved');
    // All platforms use Emby OriginalProbePath rather than host-specific guesses.
    for(const reference of ['C:\\Emby\\ffprobe.exe','/var/packages/EmbyServer/target/bin/ffprobe','/app/emby/bin/ffprobe','/opt/emby-server/bin/ffprobe','/Applications/EmbyServer/ffprobe']) {
      discovery={...discovery,path:reference,accessible:true};
      await page.locator('#probe-path').fill('');
      await page.locator('#test-emby').click();
      await page.locator('#test-emby:not(:disabled)').waitFor();
      saved=(await (await context.request.get(origin+'/api/settings')).json()).settings;
      assert(saved.upstreamProbePath===reference,'automatic discovery works for platform: '+reference);
    }
    await page.locator('#probe-path').fill('manual-mapped-probe');
    await page.locator('#test-emby').click(); await page.locator('#test-emby:not(:disabled)').waitFor();
    assert(await page.locator('#probe-path').inputValue()==='manual-mapped-probe','automatic filling preserves a configured manual or mapped path');
    discovery={...discovery,path:'/remote-container/ffprobe',accessible:false,message:'Emby 返回了原版路径，但本工具无法访问该文件。'};
    await page.locator('#discover-probe').click(); await page.locator('#discover-probe:not(:disabled)').waitFor();
    assert(await page.locator('#probe-path').inputValue()==='manual-mapped-probe','inaccessible container path cannot replace a manual path');
    assert((await page.locator('#probe-discovery-result').textContent()).includes('/remote-container/ffprobe'),'inaccessible returned path is still shown with explanation');
    await page.locator('#probe-path').fill('');
    await page.locator('#test-emby').click(); await page.locator('#test-emby:not(:disabled)').waitFor();
    assert(await page.locator('#probe-path').inputValue()==='','unavailable remote path is never saved automatically');
    discovery={path:null,accessible:false,message:'此 Emby 版本未返回原版路径，请参考下方路径手动填写。'};
    await page.locator('#discover-probe').click(); await page.locator('#discover-probe:not(:disabled)').waitFor();
    assert((await page.locator('#probe-discovery-result').textContent()).includes('未返回'),'older Emby falls back to platform references');
    discoveryError=true;
    await page.locator('#discover-probe').click(); await page.locator('#discover-probe:not(:disabled)').waitFor();
    assert((await page.locator('#probe-discovery-result').textContent()).includes('API key 验证失败'),'API error is displayed at the path field');
    discoveryError=false; discovery={path:executable,accessible:true,message:'已从 Emby 获取原版 ffprobe 路径。'};
    await page.locator('#discover-probe').click(); await page.locator('#discover-probe:not(:disabled)').waitFor();
    assert(await page.locator('#probe-path').inputValue()===executable && discoveryCalls===4,'manual discovery fills a usable path');
    await page.locator('.probe-path-help summary').click();
    for(const label of ['Windows','群晖 DSM','Docker','Linux','macOS']) assert((await page.locator('.probe-path-reference').textContent()).includes(label),'reference includes '+label);
    await screenshot('connection-reference');
    await page.setViewportSize({width:390,height:844}); await screenshot('connection-reference-mobile');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile path reference does not overflow');
    await page.setViewportSize({width:1440,height:1080});
    await page.locator('[data-page="features"]').click();
    await page.locator('#multiclip-status[data-state="off"]').waitFor();
    assert(!(await page.locator('#enable-multiclip').isChecked()),'new multi-clip feature defaults to disabled');
    const languageBefore=await page.locator('#enable-infuse').isChecked();
    await page.locator('#enable-multiclip').setChecked(true);
    await page.locator('#multiclip-status[data-state="on"]').waitFor();
    assert((await page.locator('#multiclip-status-copy').textContent()).includes('内置读取器'),'enabled feature reports built-in reader without native tools');
    assert(await page.locator('#enable-infuse').isChecked()===languageBefore,'multi-clip switch is independent from language patching');
    assert((await (await context.request.get(origin+'/api/settings')).json()).settings.enableInfuseMultiClipPlayback,'multi-clip switch persists immediately without saving the form');
    await page.route('**/api/infuse/multiclip',route=>route.request().method()==='POST'?route.fulfill({status:400,json:{error:'fixture: 无法保存开关'}}):route.continue(),{times:1});
    await page.locator('#enable-multiclip').setChecked(false);
    await page.locator('#toast').filter({hasText:'无法保存开关'}).waitFor();
    await page.locator('#enable-multiclip:not(:disabled)').waitFor();
    assert(await page.locator('#enable-multiclip').isChecked(),'failed toggle restores the saved state');
    await page.locator('.multiclip-help summary').click();
    await screenshot('multiclip-settings');
    await page.setViewportSize({width:390,height:844}); await screenshot('multiclip-settings-mobile');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile multi-clip explanation has no horizontal overflow');
    await page.setViewportSize({width:1440,height:1080});
    await page.locator('#enable-multiclip').setChecked(false);
    await page.locator('#multiclip-status[data-state="off"]').waitFor();
    await page.locator('[data-page="overview"]').click(); await screenshot('three-features');
    assert(await page.locator('.feature-card').count()===3,'overview displays all three independent features');
    await page.locator('[data-page="logs"]').click();
    let clears=0, failClear=true, staleResponse;
    const oldLog={time:new Date().toISOString(),level:'Information',source:'Fixture',message:'old-log-before-clear'};
    await page.route('**/api/logs/clear',async route=>{
      clears++;
      return failClear ? route.fulfill({status:400,json:{error:'fixture: 日志文件无法删除'}}) : route.fulfill({json:{message:'全部运行日志已清除。'}});
    });
    await page.locator('#clear-logs').click();
    assert((await page.locator('#dialog-copy').textContent()).includes('历史日志') && (await page.locator('#dialog-confirm').textContent())==='清除全部','confirmation describes deleting the entire log history');
    await page.locator('#dialog-cancel').click();
    assert(clears===0,'cancel does not delete logs');
    await page.locator('#clear-logs').click(); await page.locator('#dialog-confirm').click();
    await page.locator('#toast').filter({hasText:'日志文件无法删除'}).waitFor();
    assert(clears===1,'failure surfaces to the user');
    // Hold an old polling response across deletion to ensure stale entries cannot reappear.
    const staleReceived=new Promise(resolve=>staleResponse=resolve);
    let releaseLogs;
    const heldLogs=new Promise(resolve=>releaseLogs=resolve);
    await page.route('**/api/logs',async route=>{
      staleResponse(); await heldLogs;
      await route.fulfill({json:[oldLog]});
    },{times:1});
    await page.evaluate(()=>{
      const originalRefresh=refresh;
      window.heldLogRefresh=new Promise(resolve=>{
        refresh=async()=>{try{await originalRefresh();}finally{refresh=originalRefresh;resolve();}};
      });
    });
    await page.clock.fastForward(5000); await staleReceived;
    failClear=false;
    await page.locator('#clear-logs').click(); await page.locator('#dialog-confirm').click();
    await page.locator('#toast').filter({hasText:'全部运行日志已清除'}).waitFor();
    assert(await page.locator('#log-rows tr').count()===0 && await page.locator('#logs-empty').isVisible(),'successful clear immediately empties the table');
    assert((await page.locator('#recent-activity').textContent()).includes('暂无活动'),'clear also updates overview recent activity');
    releaseLogs(); await page.evaluate(()=>window.heldLogRefresh);
    assert(!(await page.locator('#log-rows').textContent()).includes('old-log-before-clear'),'an in-flight pre-clear log response cannot repopulate old rows');
    assert((await page.locator('#log-count').textContent())==='0 条记录','cleared log count is zero');
    await screenshot('logs-cleared');
    await page.setViewportSize({width:390,height:844}); await screenshot('logs-cleared-mobile');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile log actions do not overflow');
    assert(errors.length===0,errors.join('\n'));
    console.log('Passed isolated UI checks: probe integration and discovery, independent multi-clip switch/status/errors, log clearing, stale responses, desktop and mobile.');
  } finally {
    if(browser) await browser.close();
    processHandle.kill();
    await new Promise(resolve=>processHandle.exitCode!==null?resolve():processHandle.once('exit',resolve));
    fs.rmSync(directory,{recursive:true,force:true});
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
