const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { JSDOM } = require(path.resolve(process.argv[2] || 'artifacts/ui-check/node_modules/jsdom'));
const root = path.resolve(__dirname, '../..');
const web = name => fs.readFileSync(path.join(root, 'src/EmbyBlurayHelper.App/Web', name), 'utf8');
const dom = new JSDOM(web('index.html'), { url:'http://localhost/#connection', runScripts:'outside-only', pretendToBeVisual:true });
const w = dom.window, d = w.document;
w.HTMLElement.prototype.scrollIntoView = function() {};
let checks = 0, savedEvents = 0, fail = false, holdPost = false, releasePost, posts = [], reads = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
let state = { serverId:'one', pluginReady:true, synchronized:true, message:'新增媒体库默认允许处理。', libraries:[
  { id:'movies', name:'Movies <tag>', collectionType:'movies', allowed:true },
  { id:'tv', name:'TV', collectionType:'tvshows', allowed:true },
  { id:'music', name:'Music', collectionType:'music', allowed:true }
] };
const response = () => ({ ...structuredClone(state), allowedCount:state.libraries.filter(l => l.allowed).length, excludedCount:state.libraries.filter(l => !l.allowed).length });
w.fetch = async (url, options) => {
  if (url !== '/api/library-scope') throw new Error('Unexpected route: ' + url);
  if (options.method === 'POST') {
    const body = JSON.parse(options.body); posts.push(body);
    if (holdPost) await new Promise(resolve => releasePost = resolve);
    if (body.serverId !== state.serverId) return { status:400, ok:false, headers:{ get:() => 'application/json' }, json:async () => ({ error:'服务器已变化' }) };
    for (const l of state.libraries) l.allowed = !body.excludedLibraryIds.includes(l.id);
  } else reads++;
  if (fail) throw new Error('读取失败');
  return { status:200, ok:true, headers:{ get:() => 'application/json' }, json:async () => response() };
};
const evaluate = code => vm.runInContext(code, dom.getInternalVMContext());
evaluate(web('app.js').replace('startConsole().catch(()=>{});', ''));
evaluate("configuration={embyUrl:'http://127.0.0.1:8096'};$('#console').hidden=false;");
evaluate(web('library-scope.js'));
w.addEventListener('helper:scope-saved', () => savedEvents++);
const settle = async () => { for (let i=0;i<5;i++) await new Promise(resolve => setImmediate(resolve)); };
const boxes = () => [...d.querySelectorAll('[data-scope-library]')];
const change = (id, checked) => { const box = d.querySelector(`[data-scope-library="${id}"]`); box.checked = checked; box.dispatchEvent(new w.Event('change', { bubbles:true })); };
(async () => {
  w.dispatchEvent(new w.Event('helper:navigate')); await settle();
  check(boxes().length === 3 && boxes().every(b => b.checked), 'first use allows movies, TV and music without type-based exclusions');
  check(d.querySelector('#scope-libraries').textContent.includes('Movies <tag>') && !d.querySelector('#scope-libraries tag'), 'library names are escaped');
  check(d.querySelector('#scope-save').disabled && d.querySelector('#scope-status').textContent.includes('允许 3 个'), 'unchanged policy is not saved again');
  check(d.querySelector('#scope-save').textContent === '已保存' && d.querySelector('#scope-save-state').textContent.includes('已保存并与 Emby 同步'), 'unchanged scope clearly explains why save is disabled');
  check(d.querySelector('#scope-save').getAttribute('aria-busy') === 'false' && d.querySelector('#scope-upgrade').hidden, 'an idle disabled button never claims to be saving or needs an update');
  change('tv', false);
  check(!d.querySelector('#scope-save').disabled && !d.querySelector('#scope-dirty').hidden, 'unsaved exclusions are explicit');
  check(d.querySelector('[data-scope-library="tv"]').closest('label').textContent.includes('已排除'), 'excluded row has a visible state');
  holdPost = true;
  d.querySelector('#scope-save').click(); await settle();
  check(d.querySelector('#scope-save').disabled && d.querySelector('#scope-save').textContent === '正在保存…' && d.querySelector('#scope-save').getAttribute('aria-busy') === 'true', 'pending request alone shows an explicit saving state');
  check(boxes().every(b => b.disabled) && d.querySelector('#scope-refresh').disabled, 'controls are locked while scope is being saved');
  const postCount = posts.length;
  d.querySelector('#scope-save').onclick(); await settle();
  check(posts.length === postCount, 'pending save cannot submit twice');
  holdPost = false; releasePost(); await settle();
  check(posts[0].serverId === 'one' && JSON.stringify(posts[0].excludedLibraryIds) === '["tv"]', 'save submits explicit exclusions tied to server ID');
  check(savedEvents === 1 && d.querySelector('#scope-save').disabled, 'successful save notifies other pages and clears dirty state');
  check(d.querySelector('#scope-save').textContent === '已保存' && d.querySelector('#scope-save').getAttribute('aria-busy') === 'false', 'successful save exits the waiting state');
  check(d.querySelector('#lib-scope-summary').textContent.includes('允许 2 / 3') && d.querySelector('#lib-scope-summary').textContent.includes('已排除 1'), 'main page summary reflects saved global scope');
  const before = reads; await settle();
  check(reads === before, 'scope is not repeatedly polled');
  state.libraries[1].name = 'Renamed TV'; state.libraries.push({ id:'new', name:'New', collectionType:'tvshows', allowed:true });
  d.querySelector('#scope-refresh').click(); await settle();
  check(!d.querySelector('[data-scope-library="tv"]').checked && d.querySelector('[data-scope-library="new"]').checked, 'rename retains exclusion and newly created library is selected');
  d.querySelector('#scope-select-none').click();
  check(boxes().every(b => !b.checked), 'exclude-all is an explicit valid choice');
  d.querySelector('#scope-save').click(); await settle();
  check(posts.at(-1).excludedLibraryIds.length === 4 && d.querySelector('#lib-scope-summary').textContent.includes('允许 0 / 4'), 'empty allowed scope never becomes an accidental process-all');
  d.querySelector('#scope-select-all').click(); d.querySelector('#scope-save').click(); await settle();
  check(posts.at(-1).excludedLibraryIds.length === 0 && boxes().every(b => b.checked), 'checking all restores processing');
  change('tv', false); state.serverId = 'two'; d.querySelector('#scope-save').click(); await settle();
  check(!d.querySelector('#scope-dirty').hidden && d.querySelector('#toast').textContent.includes('服务器已变化'), 'stale server save fails visibly without claiming success');
  check(d.querySelector('#scope-save-state').textContent.includes('保存失败：服务器已变化') && !d.querySelector('#scope-save').disabled, 'save failure stays visible and permits a retry');
  state.libraries.forEach(l => l.allowed = true); d.querySelector('#scope-refresh').click(); await settle();
  check(boxes().every(b => b.checked) && d.querySelector('#scope-save').disabled, 'switching servers displays its independent saved scope');
  state.pluginReady = false; state.synchronized = false; state.message = '需要插件 0.1.9 并重启 Emby';
  d.querySelector('#scope-refresh').click(); await settle(); change('tv', false);
  check(d.querySelector('#scope-save').disabled && d.querySelector('#scope-message').textContent.includes('重启 Emby'), 'older plugin cannot pretend to enforce automatic exclusions');
  check(!d.querySelector('#scope-upgrade').hidden && d.querySelector('#scope-save').textContent === '需要更新插件' && d.querySelector('#scope-save').getAttribute('aria-busy') === 'false', 'older plugin shows an upgrade warning rather than a waiting state');
  check(d.querySelector('#scope-save-state').textContent.includes('尚未保存'), 'blocked save never claims that the selected exclusions are active');
  check(d.querySelector('#scope-plugin-update').href === 'http://localhost:8096/web/index.html#!/configurationpage?name=EmbyBlurayHelperUpdate', 'update entry maps server loopback to the browser host');
  const blockedPosts = posts.length;
  await d.querySelector('#scope-save').onclick();
  check(posts.length === blockedPosts, 'old plugin cannot bypass disabled-button protection');
  evaluate("configuration.embyUrl='https://user:secret@nas.example/prefix/?api_key=secret';");
  d.querySelector('#scope-select-all').click();
  check(d.querySelector('#scope-plugin-update').href === 'https://nas.example/prefix/web/index.html#!/configurationpage?name=EmbyBlurayHelperUpdate', 'update link preserves proxy prefix while omitting all credentials');
  evaluate("configuration.embyUrl='javascript:alert(1)';");
  d.querySelector('#scope-select-none').click();
  check(d.querySelector('#scope-plugin-update').hidden && !d.querySelector('#scope-plugin-update').hasAttribute('href'), 'unsafe update URLs never become links');
  fail = true; d.querySelector('#scope-refresh').click(); await settle();
  check(boxes().length === 0 && d.querySelector('#scope-message').textContent.includes('读取失败') && d.querySelector('#scope-save').disabled, 'read failure clears stale server controls');
  check(d.querySelector('#scope-upgrade').hidden && d.querySelector('#scope-save-state').textContent.includes('读取失败'), 'read failure is distinct from an outdated plugin');
  w.dispatchEvent(new w.Event('helper:logout'));
  check(boxes().length === 0 && d.querySelector('#scope-save').disabled, 'logout clears library state');
  const css = web('app.css');
  check(css.includes('button:disabled{opacity:.55;cursor:default}') && css.includes('button[aria-busy="true"]{cursor:wait}'), 'disabled controls use a normal cursor and only active requests use a waiting cursor');
  console.log(`Passed ${checks} global library scope Web checks.`);
})().catch(error => { console.error(error); process.exitCode=1; }).finally(() => w.close());
