const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { JSDOM } = require(path.resolve('artifacts/ui-check/node_modules/jsdom'));
const root = path.resolve(__dirname, '../..');
const dom = new JSDOM(fs.readFileSync(path.join(root, 'src/EmbyBlurayHelper.App/Web/index.html'), 'utf8'), { url: 'http://localhost/#infuse', runScripts: 'outside-only' });
const w = dom.window, d = w.document;
vm.runInContext(fs.readFileSync(path.join(root, 'src/EmbyBlurayHelper.App/Web/app.js'), 'utf8').replace('startConsole().catch(()=>{});', ''), dom.getInternalVMContext());
const settings = { embyUrl: 'http://localhost:8096', proxyUrl: 'http://localhost:8097', managementUrl: 'http://localhost:8099', upstreamProbePath: '/original/ffprobe', embyApiKey: 'fixture', enableProbeLanguagePatch: true, enableInfuseLanguagePatch: true, enableInfuseMultiClipPlayback: true, enableInfuseChapters: false };
w.fillSettings({ settings, hasApiKey: true, executablePath: '/helper', dataDirectory: '/data' });
assert.equal(d.querySelector('#enable-infuse-chapters').checked, false);
assert.match(d.querySelector('#infuse-chapters-state').textContent, /已关闭/);
d.querySelector('#enable-infuse-chapters').checked = true;
const collected = w.collectSettings();
assert.equal(collected.enableInfuseChapters, true);
assert.equal(collected.enableInfuseMultiClipPlayback, true);
assert.equal(collected.enableProbeLanguagePatch, true);
w.fillSettings({ settings: { ...settings, enableInfuseChapters: true }, hasApiKey: true, executablePath: '/helper', dataDirectory: '/data' });
assert.match(d.querySelector('#infuse-chapters-state').textContent, /已启用/);
assert.equal(d.querySelector('#infuse-chapters-state').classList.contains('off'), false);
assert.match(d.querySelector('#infuse-chapters-panel').textContent, /默认关闭/);
assert.match(d.querySelector('#infuse-chapters-panel').textContent, /真实 ISO 暂保持原样/);
assert.ok(d.querySelector('#page-infuse #infuse-chapters-panel'));
console.log('Passed 10 Infuse chapter UI checks.');
dom.window.close();
